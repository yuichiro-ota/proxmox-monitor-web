// ---------------------------------------------------------------------------
// 系統図（トポロジ）の静的設定
// ---------------------------------------------------------------------------
// ルーター / ネットワークセグメント / クラスタ名など、Proxmox API からは
// 取得できない「構成情報」をここで定義します。
//
// ★ ここの値は環境ごとに書き換えてください（下記はプレースホルダーの例）。
//   公開リポジトリに実IP等を残さないため、既定値は汎用の例にしています。
//
// git pull 運用でローカルの編集を保持したい場合は、編集後に一度だけ:
//   git update-index --skip-worktree frontend/src/topology.js
// としておくと、以降の pull で自分の設定が上書き・コンフリクトしません。
// （戻すときは --no-skip-worktree）
//
// 将来オンプレサーバーやネットワーク機器を追加する際は `extraGroups` に
// グループを足すと、クラスタと並んで系統図に表示されます。
// ---------------------------------------------------------------------------

export const topology = {
  // 最上位のルーター（ゲートウェイ）
  // API での死活監視に対応しない機器は静的に online: true で表示します。
  // SNMP 等で死活監視する機器に変える場合は router 監視を実装して online を動的化する。
  router: {
    name: 'Router',
    ip: '192.168.1.1',
    online: true,
  },

  // ルーター配下のネットワークセグメント。複数定義可。
  // VLAN 非対応の環境では vlan は空にします。
  segments: [
    {
      cidr: '192.168.1.0/24',
      vlan: '',
      label: 'LAN',
    },
  ],

  // Proxmox クラスタの見出し。ノード自体は API から動的に取得します。
  cluster: {
    name: 'Proxmox cluster',
    // クラスタをぶら下げるセグメント（segments の cidr）。null なら先頭に接続。
    segment: '192.168.1.0/24',
  },

  // 将来追加するグループ（例: オンプレサーバー, ネットワーク機器）。
  // 空配列の間は系統図に表示されません。
  //   { name: 'オンプレサーバー', segment: '192.168.10.0/24', items: [...] }
  extraGroups: [],
}
